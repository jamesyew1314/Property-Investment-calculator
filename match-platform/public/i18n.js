export function makeT(lang) {
  const dict = I18N[lang] || I18N.zh;
  return function t(key, params = {}) {
    let s = dict[key];
    if (s == null) s = I18N.zh[key];
    if (s == null) return key;
    return String(s).replace(/\{(\w+)\}/g, (m, name) =>
      params[name] == null ? m : String(params[name])
    );
  };
}
