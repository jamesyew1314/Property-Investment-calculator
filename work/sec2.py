    para(doc, "S&P 报价单有 “Total for 1 Purchaser” 和 “Total for 2 Purchaser” 两列；贷款报价单有 “Total for 1 / 2 Borrower”。两者的差额是固定的：S&P 差 RM486，贷款差 RM162，不随价格变化。这说明它不是按比例收的，而是一个固定的附加项（第二份文件/第二位签署人的 stamping 或杂费）。系统应把它做成“按人数 × 固定费”，而不是乘一个百分比。", size=9.8)

